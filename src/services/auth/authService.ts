/**
 * Authentication — anonymous-first, linkable later (DECISIONS.md D-003).
 *
 * The player is signed in before they ever see a menu, with no login screen.
 * A real account is only ever offered as a way to protect progress, never as
 * a gate on play.
 *
 * Recovery ladder, weakest to strongest:
 *   1. Anonymous UID           — survives uninstall on iOS (Keychain) but NOT
 *                                on Android (SharedPreferences is wiped).
 *   2. Play Games / Game Center — silent, no UI, tied to the device account.
 *                                This is what makes Android reinstalls recover.
 *   3. Google / Apple link      — offered by the milestone nudge. Definitive.
 *
 * Premium entitlement is deliberately NOT in this ladder: it restores through
 * the App Store / Play receipt, independent of Firebase. A player who loses
 * coins never loses what they paid for.
 */

import {
  getAuth,
  getIdToken,
  reauthenticateWithCredential,
  deleteUser,
  signInAnonymously,
  GoogleAuthProvider,
  linkWithCredential,
  signInWithCredential,
  type AuthCredential,
  type User,
} from "@react-native-firebase/auth";
import { NativeModules, Platform } from "react-native";
import {
  GoogleSignin,
  isSuccessResponse,
} from "@react-native-google-signin/google-signin";

export type AuthProvider =
  | "anonymous"
  | "playGames"
  | "gameCenter"
  | "google"
  | "apple";

export type AuthUser = {
  uid: string;
  isAnonymous: boolean;
  /** True once any durable provider is linked — drives the nudge. */
  hasRecoverableIdentity: boolean;
  providers: AuthProvider[];
};

function toAuthUser(user: User): AuthUser {
  const providers = user.providerData.map((p: { providerId: string }) => {
    switch (p.providerId) {
      case "google.com":
        return "google" as const;
      case "apple.com":
        return "apple" as const;
      case "playgames.google.com":
        return "playGames" as const;
      case "gc.apple.com":
        return "gameCenter" as const;
      default:
        return "anonymous" as const;
    }
  });

  const durable = providers.filter((p: AuthProvider) => p !== "anonymous");

  return {
    uid: user.uid,
    isAnonymous: user.isAnonymous,
    hasRecoverableIdentity: durable.length > 0,
    providers: durable.length > 0 ? durable : ["anonymous"],
  };
}

/**
 * Signs in anonymously if there is no current user. Call once at launch.
 *
 * Cheap when a user already exists — Firebase restores the session from local
 * storage without a network round-trip, which is why this can sit on the
 * startup path without costing launch time.
 */
export async function ensureSignedIn(): Promise<AuthUser> {
  const auth = getAuth();
  if (auth.currentUser) {
    return toAuthUser(auth.currentUser);
  }
  const credential = await signInAnonymously(auth);
  return toAuthUser(credential.user);
}

export function getCurrentUser(): AuthUser | null {
  const user = getAuth().currentUser;
  return user ? toAuthUser(user) : null;
}

/** The uid the sync queue writes under, or null before sign-in completes. */
export function getCurrentUid(): string | null {
  return getAuth().currentUser?.uid ?? null;
}

/** Read OAuth IDs generated by the native Firebase configuration, never secrets. */
function configuration(): {
  googleWebClientId?: string;
  googleIosClientId?: string;
} {
  return NativeModules.GridLockFeedback ?? {};
}
export function isAccountLinkingConfigured(): boolean {
  const config = configuration();
  return Platform.OS === "android"
    ? Boolean(config.googleWebClientId)
    : Boolean(config.googleIosClientId);
}
function configureGoogle(): void {
  if (!isAccountLinkingConfigured()) {
    throw new AccountLinkingUnavailableError();
  }
  const config = configuration();
  GoogleSignin.configure({
    ...(config.googleWebClientId
      ? { webClientId: config.googleWebClientId }
      : {}),
    ...(config.googleIosClientId
      ? { iosClientId: config.googleIosClientId }
      : {}),
  });
}
export class AccountLinkingUnavailableError extends Error {
  constructor() {
    super("Google sign-in is not configured for this build.");
    this.name = "AccountLinkingUnavailableError";
  }
}
export class AccountLinkCancelledError extends Error {
  constructor() {
    super("Sign-in cancelled. Your local save is unchanged.");
  }
}
let pendingCredential: AuthCredential | null = null;
export class ExistingGoogleSaveError extends Error {
  constructor() {
    super("This Google account already has a save.");
    this.name = "ExistingGoogleSaveError";
  }
}
export function dismissExistingGoogleSave(): void {
  pendingCredential = null;
}

/** No account switch occurs without an explicit conflict confirmation. */
export async function linkAccount(
  provider: "google" | "apple"
): Promise<AuthUser> {
  if (provider !== "google") {
    throw new AccountLinkingUnavailableError();
  }
  configureGoogle();
  await ensureSignedIn();
  if (Platform.OS === "android") {
    await GoogleSignin.hasPlayServices({ showPlayServicesUpdateDialog: true });
  }
  const response = await GoogleSignin.signIn();
  if (!isSuccessResponse(response)) {
    throw new AccountLinkCancelledError();
  }
  if (!response.data.idToken) {
    throw new Error("Google did not return a sign-in token.");
  }
  const credential = GoogleAuthProvider.credential(response.data.idToken);
  const user = getAuth().currentUser!;
  if (!user.isAnonymous) {
    return toAuthUser(user);
  }
  try {
    const linked = await linkWithCredential(user, credential);
    pendingCredential = null;
    return toAuthUser(linked.user);
  } catch (error) {
    const code = (error as { code?: string }).code;
    if (
      code === "auth/credential-already-in-use" ||
      code === "auth/email-already-in-use"
    ) {
      pendingCredential = credential;
      throw new ExistingGoogleSaveError();
    }
    throw error;
  }
}

/** Called only after the player approves using the existing cloud balance. */
export async function signInExistingGoogleSave(): Promise<AuthUser> {
  if (!pendingCredential) {
    throw new Error("Choose your Google account again.");
  }
  const result = await signInWithCredential(getAuth(), pendingCredential);
  pendingCredential = null;
  return toAuthUser(result.user);
}

/** Silent linking is deliberately limited to an already selected Google account. */
export async function trySilentPlatformLink(): Promise<boolean> {
  if (!isAccountLinkingConfigured() || !getAuth().currentUser?.isAnonymous) {
    return false;
  }
  try {
    configureGoogle();
    if (!GoogleSignin.hasPreviousSignIn()) {
      return false;
    }
    const response = await GoogleSignin.signInSilently();
    if (response.type !== "success" || !response.data.idToken) {
      return false;
    }
    await linkWithCredential(
      getAuth().currentUser!,
      GoogleAuthProvider.credential(response.data.idToken)
    );
    return true;
  } catch {
    return false;
  }
}

/** Explicit deletion only: reauthentication cannot switch the Firebase account. */
export async function verifyDeletionIdentity(uid: string): Promise<void> {
  const user = getAuth().currentUser;
  if (!user || user.uid !== uid) throw new Error("deletion/account-changed");
  if (user.isAnonymous) {
    await getIdToken(user, true);
    return;
  }
  if (!user.providerData.some((p) => p.providerId === "google.com"))
    throw new Error("deletion/unsupported-provider");
  configureGoogle();
  if (Platform.OS === "android")
    await GoogleSignin.hasPlayServices({ showPlayServicesUpdateDialog: true });
  const response = await GoogleSignin.signIn();
  if (!isSuccessResponse(response)) throw new AccountLinkCancelledError();
  if (!response.data.idToken) throw new Error("deletion/no-token");
  await reauthenticateWithCredential(
    user,
    GoogleAuthProvider.credential(response.data.idToken)
  );
  if (getAuth().currentUser?.uid !== uid)
    throw new Error("deletion/account-changed");
}
export async function removeAuthenticatedAccount(uid: string): Promise<void> {
  const user = getAuth().currentUser;
  if (!user || user.uid !== uid) throw new Error("deletion/account-changed");
  await deleteUser(user);
  pendingCredential = null;
  // Sign out of the app's Google session, not the device's Google account.
  try {
    if (GoogleSignin.hasPreviousSignIn()) await GoogleSignin.signOut();
  } catch {
    /* Firebase account is already deleted. */
  }
}
